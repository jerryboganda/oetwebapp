import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import {
  WEBSITE_PACKAGES,
  resolveWebsitePackageByCode,
  websitePackageCheckoutHref,
  websitePackagePurchaseHref,
} from './catalog-website-packages';

interface MarkdownPackage {
  packageNo: number;
  name: string;
  profession: string;
  duration?: string;
  category: string;
  description: string;
  access: string;
  formatLine: string;
  features: string[];
  bestFor: string;
}

interface SeedCatalogRow {
  code: string;
  description: string;
  price: number;
  originalPrice: number | null;
}

interface SeedCatalogPlan extends SeedCatalogRow {
  comparisonFeatures: string[];
  isDraft: boolean;
  isVisible: boolean;
}

interface SeedCatalogAddOn extends SeedCatalogRow {
  addonKind: string;
  aiFeatures?: string[];
}

interface SeedCatalogManifest {
  plans: SeedCatalogPlan[];
  addOns: SeedCatalogAddOn[];
}

const CANONICAL_MARKDOWN_PATH = join(
  process.cwd(),
  'docs',
  'OET_2026_Complete_Website_Course_and_Package_Descriptions.md',
);
const BACKEND_MANIFEST_PATH = join(
  process.cwd(),
  'backend',
  'src',
  'OetLearner.Api',
  'Data',
  'Seeds',
  'oet-2026-catalog.json',
);

function requiredMatch(body: string, pattern: RegExp, label: string): RegExpMatchArray {
  const match = body.match(pattern);
  if (!match) throw new Error(`Missing ${label} in canonical catalogue block`);
  return match;
}

function parseCanonicalCatalogue(markdown: string): MarkdownPackage[] {
  const headings = [...markdown.matchAll(/^### (\d+)\. (.+)$/gm)];
  return headings.map((heading, index) => {
    const start = (heading.index ?? 0) + heading[0].length;
    const end = headings[index + 1]?.index ?? markdown.length;
    const body = markdown.slice(start, end);
    const metadata = requiredMatch(
      body,
      /^\*\*Profession:\*\* (.+?)(?: \| \*\*Duration:\*\* (.+?))? \| \*\*Category:\*\* (.+)$/m,
      'profession/category metadata',
    );
    const description = requiredMatch(
      body,
      /^\*\*Website description:\*\* (.+)$/m,
      'website description',
    );
    const accessAndFormat = requiredMatch(
      body,
      /^\*\*Access:\*\* (.+?) \| \*\*Format:\*\* (.+)$/m,
      'access/format metadata',
    );
    const included = requiredMatch(
      body,
      /^#### Included components\s+([\s\S]*?)^\*\*Best for:\*\* (.+)$/m,
      'included components and Best for',
    );

    return {
      packageNo: Number(heading[1]),
      name: heading[2].trim(),
      profession: metadata[1].trim(),
      duration: metadata[2]?.trim(),
      category: metadata[3].trim(),
      description: description[1].trim(),
      access: accessAndFormat[1].trim(),
      formatLine: accessAndFormat[2].trim(),
      features: included[1]
        .split(/\r?\n/)
        .filter((line) => line.startsWith('- '))
        .map((line) => line.slice(2).trim()),
      bestFor: included[2].trim(),
    };
  });
}

describe('canonical 2026 website package catalogue', () => {
  it('matches every field and component in the canonical Markdown for all 48 packages', () => {
    const markdown = readFileSync(CANONICAL_MARKDOWN_PATH, 'utf8');
    const canonical = parseCanonicalCatalogue(markdown);

    expect(canonical).toHaveLength(48);
    expect(canonical.map((pkg) => pkg.packageNo)).toEqual(
      Array.from({ length: 48 }, (_, index) => index + 1),
    );
    expect(
      WEBSITE_PACKAGES.map(
        ({
          packageNo,
          name,
          profession,
          duration,
          category,
          description,
          access,
          formatLine,
          features,
          bestFor,
        }) => ({
          packageNo,
          name,
          profession,
          duration,
          category,
          description,
          access,
          formatLine,
          features,
          bestFor,
        }),
      ),
    ).toEqual(canonical);
  });

  it('keeps backend seed descriptions and feature arrays aligned to the canonical Markdown', () => {
    const canonical = parseCanonicalCatalogue(readFileSync(CANONICAL_MARKDOWN_PATH, 'utf8'));
    const manifest = JSON.parse(
      readFileSync(BACKEND_MANIFEST_PATH, 'utf8'),
    ) as SeedCatalogManifest;
    const canonicalByNumber = new Map(canonical.map((pkg) => [pkg.packageNo, pkg]));
    const plansByCode = new Map(manifest.plans.map((plan) => [plan.code, plan]));
    const addOnsByCode = new Map(manifest.addOns.map((addOn) => [addOn.code, addOn]));

    for (const pkg of WEBSITE_PACKAGES) {
      const markdownPackage = canonicalByNumber.get(pkg.packageNo);
      expect(markdownPackage, `Markdown package ${pkg.packageNo}`).toBeDefined();

      if (pkg.productType === 'plan_purchase') {
        const seedPlan = plansByCode.get(pkg.code);
        expect(seedPlan, `backend plan ${pkg.code}`).toBeDefined();
        expect(seedPlan?.description).toBe(markdownPackage?.description);
        expect(seedPlan?.comparisonFeatures).toEqual(markdownPackage?.features);
        continue;
      }

      const seedAddOn = addOnsByCode.get(pkg.code);
      expect(seedAddOn, `backend add-on ${pkg.code}`).toBeDefined();
      expect(seedAddOn?.description).toBe(markdownPackage?.description);

      if (pkg.packageNo >= 30 && pkg.packageNo <= 47) {
        expect(seedAddOn?.addonKind).toBe('ai_package');
        expect(seedAddOn?.aiFeatures).toEqual(markdownPackage?.features);
      } else {
        expect([13, 14, 15, 16, 29]).toContain(pkg.packageNo);
      }
    }
  });

  it('keeps operational price and publication status outside the Markdown-owned copy', () => {
    const markdown = readFileSync(CANONICAL_MARKDOWN_PATH, 'utf8');
    const canonical = parseCanonicalCatalogue(markdown);
    const manifest = JSON.parse(
      readFileSync(BACKEND_MANIFEST_PATH, 'utf8'),
    ) as SeedCatalogManifest;

    expect(markdown).not.toMatch(
      /^\*\*(?:Price|Original price|Status|Draft|Visible):\*\*/im,
    );
    for (const pkg of canonical) {
      expect(pkg).not.toHaveProperty('price');
      expect(pkg).not.toHaveProperty('originalPrice');
      expect(pkg).not.toHaveProperty('status');
      expect(pkg).not.toHaveProperty('isDraft');
      expect(pkg).not.toHaveProperty('isVisible');
    }
    for (const row of [...manifest.plans, ...manifest.addOns]) {
      expect(Number.isFinite(row.price)).toBe(true);
    }
    for (const plan of manifest.plans) {
      expect(typeof plan.isDraft).toBe('boolean');
      expect(typeof plan.isVisible).toBe('boolean');
    }
  });

  it('accepts historical speaking billing codes without changing canonical codes', () => {
    expect(resolveWebsitePackageByCode('speaking-1session-plan')?.code).toBe('speaking-1session');
    expect(resolveWebsitePackageByCode('speaking-2sessions-plan')?.code).toBe('speaking-2sessions');
  });

  it('routes plans and add-ons to their valid purchase surfaces', () => {
    for (const pkg of WEBSITE_PACKAGES) {
      const href = websitePackagePurchaseHref(pkg);
      if (pkg.productType === 'plan_purchase') {
        expect(href).toBe(`/marketplace/packages/${encodeURIComponent(pkg.slug)}`);
      } else if (pkg.packageNo >= 30 && pkg.packageNo <= 47) {
        expect(href).toBe(`/ai-packages?package=${encodeURIComponent(pkg.slug)}`);
      } else {
        expect(href).toBe(`/subscriptions?package=${encodeURIComponent(pkg.slug)}`);
      }
    }

    const tutorBook = resolveWebsitePackageByCode('tutor-book');
    const standardPlan = resolveWebsitePackageByCode('full-condensed-medicine');
    expect(tutorBook && websitePackageCheckoutHref(tutorBook)).toBe(
      '/subscriptions?package=tutorbook-first-edition-2026',
    );
    expect(standardPlan && websitePackageCheckoutHref(standardPlan, 'live-plan-code')).toBe(
      '/checkout/review?productType=plan_purchase&priceId=live-plan-code&quantity=1',
    );
  });
});
